def test_parse_platform_constructs():
    # конструкции сверены с официальным синтаксис-помощником (shquery_ru.hbk)
    # СГРУППИРОВАТЬ ПО ГРУППИРУЮЩИМ НАБОРАМ (GROUPStatement)
    parse_query(
        'ВЫБРАТЬ Т.Склад, СУММА(Т.Кол) КАК Кол ИЗ РегистрНакопления.Р КАК Т '
        'СГРУППИРОВАТЬ ПО ГРУППИРУЮЩИМ НАБОРАМ ((Т.Склад), (Т.Склад, Т.Товар))')
    # В ИЕРАРХИИ (CompareB2)
    parse_query('ВЫБРАТЬ Т.Ссылка ИЗ Справочник.С1 КАК Т '
                'ГДЕ Т.Ссылка В ИЕРАРХИИ (&Г)')
    # упорядочивание по иерархии (hierarchical_ordering)
    parse_query('ВЫБРАТЬ Т.Наименование ИЗ Справочник.С1 КАК Т '
                'УПОРЯДОЧИТЬ ПО Т.Наименование ИЕРАРХИЯ УБЫВ')
    # АВТОУПОРЯДОЧИВАНИЕ (ShqueryText)
    parse_query('ВЫБРАТЬ Т.Х ИЗ Документ.Д КАК Т АВТОУПОРЯДОЧИВАНИЕ')
    # ИТОГИ без списка агрегатов, ТОЛЬКО ИЕРАРХИЯ, КАК-псевдоним
    parse_query('ВЫБРАТЬ Т.Товар, СУММА(Т.Кол) ИЗ Документ.Д КАК Т '
                'СГРУППИРОВАТЬ ПО Т.Товар '
                'ИТОГИ ПО Т.Товар ТОЛЬКО ИЕРАРХИЯ КАК Товары')
    parse_query('ВЫБРАТЬ Т.Х ИЗ Документ.Д КАК Т ИТОГИ СУММА(Т.Х) ПО ОБЩИЕ')
    parse_query('ВЫБРАТЬ Т.Х ИЗ Документ.Д КАК Т ИТОГИ ОБЩИЕ')
    # ПЕРИОДАМИ (query_totals)
    parse_query('ВЫБРАТЬ Т.Дата ИЗ Документ.Д КАК Т '
                'ИТОГИ ПО Т.Дата ПЕРИОДАМИ(ГОД, &Н, &К)')
    # псевдонимы без КАК (FromStatement, pseudonim_fields)
    st = parse_query('ВЫБРАТЬ Т.Х Сумма ИЗ Документ.Д Т')
    assert st[0]['source']['base'][-1] == 'Т'
    assert st[0]['items'][0][2] == 'Сумма'


